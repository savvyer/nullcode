/**
 * Write plugins/DEPS.md: direct external dependencies per workspace package and who pulls the heaviest trees.
 *   node --import tsx/esm plugins/scripts/deps-report.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import yaml from 'js-yaml'
import { join } from 'node:path'
import { ROOT, dependents, directDependencies, externalPackages, packageName, readLockfile } from './lockfile.ts'

const lock = readLockfile()
const all = externalPackages(lock)
const direct = directDependencies(lock)
const reverse = dependents(lock)
const forward = new Map<string, Set<string>>()
for (const [child, parents] of reverse) for (const parent of parents) {
  let set = forward.get(parent)
  if (set === undefined) forward.set(parent, set = new Set())
  set.add(child)
}
const closure = (start: string): Set<string> => {
  const seen = new Set<string>()
  const stack = [...forward.get(start) ?? []]
  while (stack.length > 0) {
    const key = stack.pop()!
    if (seen.has(key)) continue
    seen.add(key)
    stack.push(...forward.get(key) ?? [])
  }
  return seen
}

const uniqueDirect = new Map<string, { kinds: Set<string>, importers: Set<string> }>()
for (const dep of direct) {
  const key = `${dep.name}@${dep.version}`
  const entry = uniqueDirect.get(key) ?? { kinds: new Set(), importers: new Set() }
  entry.kinds.add(dep.kind)
  entry.importers.add(dep.importer)
  uniqueDirect.set(key, entry)
}
const runtime = [...uniqueDirect].filter(([, value]) => value.kinds.has('runtime'))
const heavy = [...uniqueDirect.keys()].map(key => ({ key, size: closure(key).size })).sort((a, b) => b.size - a.size).slice(0, 40)
const workspace = yaml.load(readFileSync(join(ROOT, 'pnpm-workspace.yaml'), 'utf8')) as { allowBuilds?: Record<string, boolean> }
const builds = Object.entries(workspace.allowBuilds ?? {}).map(([name, allowed]) => `${name} (${allowed ? 'allowed' : 'denied'})`)
const groups = [
  ['browser-use / computer-use / cua', /browser-use|computer-use|cua|stagehand|puppeteer|playwright|chrome-devtools/u],
] as const

const lines = [
  '# nullcode — dependency report',
  '',
  `Generated by \`plugins/scripts/deps-report.ts\` from pnpm-lock.yaml. Gate: \`plugins/scripts/check-deps.ts\` against \`plugins/deps-allowlist.json\`.`,
  '',
  `- packages in lockfile: **${all.length}** (${new Set(all.map(packageName)).size} distinct names)`,
  `- direct external dependencies (unique name@version): **${uniqueDirect.size}**, of them runtime: **${runtime.length}**`,
  `- install scripts reviewed in pnpm-workspace.yaml \`allowBuilds\`: ${builds.join(', ')}`,
  '',
  '## Reduction candidates',
  '',
  ...groups.flatMap(([title, pattern]) => {
    const hits = [...uniqueDirect].filter(([key]) => pattern.test(key))
    return [`### ${title}`, '', ...hits.map(([key, value]) => `- \`${key}\` — ${closure(key).size} transitive; used by ${[...value.importers].join(', ')}`), '']
  }),
  '## Heaviest direct dependencies (transitive closure size)',
  '',
  '| package | transitive | kind | used by |',
  '|---|---:|---|---|',
  ...heavy.map(({ key, size }) => {
    const value = uniqueDirect.get(key)!
    return `| \`${key}\` | ${size} | ${[...value.kinds].join(', ')} | ${[...value.importers].slice(0, 4).join(', ')}${value.importers.size > 4 ? ` +${value.importers.size - 4}` : ''} |`
  }),
  '',
  '## Runtime direct dependencies',
  '',
  ...runtime.sort(([a], [b]) => a.localeCompare(b)).map(([key, value]) => `- \`${key}\` — ${[...value.importers].join(', ')}`),
  '',
]
writeFileSync(join(ROOT, 'plugins', 'DEPS.md'), lines.join('\n'))
console.log(`deps-report: ${all.length} packages, ${uniqueDirect.size} direct, ${runtime.length} runtime → plugins/DEPS.md`)
